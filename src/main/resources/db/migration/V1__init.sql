-- Users who can sign in. Usernames and e-mails are stored lower-case, so UNIQUE is case-insensitive.
CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            VARCHAR(30)  NOT NULL UNIQUE,
    email               VARCHAR(120) NOT NULL UNIQUE,
    full_name           VARCHAR(100) NOT NULL,
    password_hash       VARCHAR(100) NOT NULL,
    role                VARCHAR(20)  NOT NULL,
    enabled             BOOLEAN      NOT NULL DEFAULT TRUE,
    failed_attempts     INT          NOT NULL DEFAULT 0,
    locked_until        TIMESTAMP WITH TIME ZONE,
    -- Bumped on password change, role change, "log out everywhere" and disable:
    -- every access token carries the version it was issued with, so older tokens stop working at once.
    token_version       INT          NOT NULL DEFAULT 0,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    last_login_at       TIMESTAMP WITH TIME ZONE,
    password_changed_at TIMESTAMP WITH TIME ZONE
);

-- Refresh tokens. Only a SHA-256 hash is stored, never the token itself.
-- All tokens of one sign-in share a family_id (= the session). Each refresh rotates to a new token;
-- presenting an already-rotated token means it was stolen, and the whole family is revoked.
CREATE TABLE refresh_tokens (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash         VARCHAR(64) NOT NULL UNIQUE,
    family_id          VARCHAR(36) NOT NULL,
    session_started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at         TIMESTAMP WITH TIME ZONE,
    revoke_reason      VARCHAR(30),
    replaced_by_id     BIGINT,
    user_agent         VARCHAR(255),
    ip_address         VARCHAR(45)
);
CREATE INDEX idx_refresh_family ON refresh_tokens (family_id);
CREATE INDEX idx_refresh_user ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_expires ON refresh_tokens (expires_at);

-- Security audit log: sign-ins, failures, lockouts, token reuse, role changes...
CREATE TABLE security_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    type        VARCHAR(40)  NOT NULL,
    user_id     BIGINT,
    username    VARCHAR(120),
    actor       VARCHAR(30),
    ip_address  VARCHAR(45),
    detail      VARCHAR(255)
);
CREATE INDEX idx_events_time ON security_events (occurred_at);
CREATE INDEX idx_events_user ON security_events (user_id);
